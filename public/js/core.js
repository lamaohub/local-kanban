export async function retryUnsaved() {
  if (retrying) return retrying;
  retrying = offlineRetries.retry();
  try { await retrying; } finally { retrying = null; }
  showOfflineBadge(offlineRetries.size > 0);
  if (offlineRetries.size) resendLater(); else resendTries = 0;
}
