export function onApiWarning(fn) { warned = fn; }

export const api = async (method, path, body, opts = {}) => {
  const res = await fetch(path, {
    method,
    headers: body ? { 'Content-Type': 'application/json' } : undefined,
    body: body ? JSON.stringify(body) : undefined,
    signal: opts.signal,
  }).catch((e) => {
    if (e?.name === 'AbortError') throw apiError(e.message, { aborted: true });
    if (!opts.quiet) reportError(`${method} ${path}`, `network: ${e.message}`);
    throw apiError(e.message, { offline: true });
  });
  if (res.status === 204) return null;
  const data = await answerOf(res, `${method} ${path}`, opts);
  if (!res.ok) {
    if (!opts.quiet && path !== '/api/errors') reportError(`${method} ${path}`, `HTTP ${res.status}: ${data.error || ''}`.trim());
    throw apiError(data.error || res.status, { status: res.status, body: data });
  }
  if (data?.warning && warned) warned(data.warning);
  return data;
};

export const CURTAIN_KEY = 'kb.session.curtain';
const CURTAIN_MS = 220;
const BEFORE_MAX_MS = 3000;
export async function smoothReload(before) {
  const html = document.documentElement;
  const bg = getComputedStyle(document.body).backgroundColor;
  try { sessionStore.setItem(CURTAIN_KEY, bg); } catch { /* no storage — the next page comes without the cover */ }
  html.style.setProperty('--curtain', bg);
  html.classList.remove('kb-curtain-out');
  html.classList.add('kb-curtain', 'kb-curtain-in');
  const calm = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
  const sent = Promise.race([Promise.resolve(before).catch(() => {}), new Promise((resolve) => { setTimeout(resolve, BEFORE_MAX_MS); })]);
  await Promise.all([sent, new Promise((resolve) => { setTimeout(resolve, calm ? 0 : CURTAIN_MS); })]);
  location.reload();
}
/** Takes the cover of a smooth reload off; nothing to do when there is none. */
export function liftCurtain() {
  const html = document.documentElement;
  if (!html.classList.contains('kb-curtain') || html.classList.contains('kb-curtain-out')) return;
  html.classList.add('kb-curtain-out');
  setTimeout(() => html.classList.remove('kb-curtain', 'kb-curtain-in', 'kb-curtain-out'), CURTAIN_MS + 120);
}
